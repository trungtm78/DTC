import { THEME_COLOR_KEYS } from './theme-rules.ts';
import type { DesignTokens, ThemeColors, Tokens } from './types.ts';

export const DESIGN_TOKENS_PATH = 'Design/MACHVON_Design/04_Design_Assets/design_tokens.json';
export const CSS_OUTPUT_PATH = 'packages/design-tokens/dist-css/tokens.css';
export const TS_OUTPUT_PATH = 'packages/design-tokens/src/tokens.generated.ts';

const GENERATED_NOTICE = `Generated by packages/design-tokens/src/generate.ts from ${DESIGN_TOKENS_PATH}. Do not edit; run \`npm run tokens:generate\`.`;
const PREFIX = '--mv-';

/** `textSecondary` to `text-secondary`, `ios_pt` to `ios-pt`. */
export function kebabCase(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/_/g, '-').toLowerCase();
}

function colour(json: DesignTokens, name: string): string {
  const value = json.color[name];
  if (value === undefined) throw new Error(`design tokens: colour ${name} is missing`);
  return value;
}

/**
 * The base tenant theme: which design token each overridable colour starts from. A tenant overlay replaces
 * single colours of this set (SAS-04); everything else in the design tokens stays fixed.
 */
function baseTenantTheme(json: DesignTokens): ThemeColors {
  const selectedText = json.businessNavigation.selectedText;
  if (typeof selectedText !== 'string') throw new Error('design tokens: businessNavigation.selectedText is missing');
  return {
    primary: colour(json, 'primary'),
    primaryText: colour(json, 'surface'),
    menu: colour(json, 'sidebar'),
    menuText: colour(json, 'textSecondary'),
    selected: colour(json, 'selected'),
    selectedText,
    headerBg: colour(json, 'surface'),
    headerText: colour(json, 'ink'),
    footerBg: colour(json, 'surface'),
    footerText: colour(json, 'textSecondary'),
    background: colour(json, 'background'),
    titleColor: colour(json, 'ink'),
  };
}

/** The design tokens with the base tenant theme attached. */
export function buildTokens(json: DesignTokens): Tokens {
  return { ...json, tenantTheme: baseTenantTheme(json) };
}

/** The twelve theme colours as custom properties, one per line. */
export function themeDeclarations(theme: ThemeColors, indent: string): string[] {
  return THEME_COLOR_KEYS.map((key) => `${indent}${PREFIX}theme-${kebabCase(key)}: ${theme[key]};`);
}

function declarations(tokens: Tokens): string[] {
  const lines: string[] = [];
  for (const [name, value] of Object.entries(tokens.color)) lines.push(`  ${PREFIX}color-${kebabCase(name)}: ${value};`);
  lines.push(...themeDeclarations(tokens.tenantTheme, '  '));
  lines.push(`  ${PREFIX}font-family: ${tokens.font.family};`);
  for (const [name, value] of Object.entries(tokens.font)) {
    if (typeof value === 'number') lines.push(`  ${PREFIX}font-${kebabCase(name)}: ${value}px;`);
  }
  for (const step of tokens.space) lines.push(`  ${PREFIX}space-${step}: ${step}px;`);
  for (const [name, value] of Object.entries(tokens.radius)) lines.push(`  ${PREFIX}radius-${kebabCase(name)}: ${value}px;`);
  const navigation = tokens.businessNavigation;
  lines.push(
    `  ${PREFIX}nav-sidebar-width: ${navigation.sidebarWidth}px;`,
    `  ${PREFIX}nav-compact-sidebar-width: ${navigation.compactSidebarWidth}px;`,
    `  ${PREFIX}nav-mobile-drawer-breakpoint: ${navigation.mobileDrawerBreakpoint}px;`,
    `  ${PREFIX}nav-inbox-single-pane-breakpoint: ${navigation.inboxSinglePaneBreakpoint}px;`,
  );
  return lines;
}

/**
 * Pure and deterministic: the CSS custom properties and the typed TypeScript module for the web, both from
 * the one design token file, so a change to a token changes every output in the same commit.
 */
export function generateTokens(json: DesignTokens): { css: string; ts: string } {
  const tokens = buildTokens(json);
  const css = [`/* ${GENERATED_NOTICE} */`, ':root {', ...declarations(tokens), '}', ''].join('\n');
  const ts = [
    `// ${GENERATED_NOTICE}`,
    "import type { Tokens } from './types.ts';",
    '',
    `export const TOKENS: Tokens = ${JSON.stringify(tokens, null, 2)};`,
    '',
  ].join('\n');
  return { css, ts };
}
