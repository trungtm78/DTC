import { buildTokens, DESIGN_TOKENS_PATH } from './generate.ts';
import { CONTRAST_PAIRS, MIN_TEXT_CONTRAST, THEME_COLOR_KEYS } from './theme-rules.ts';
import type { DesignTokens } from './types.ts';

export const DART_OUTPUT_PATH = 'packages/mobile-tokens/lib/machvon_theme.generated.dart';

const GENERATED_NOTICE = `Generated by packages/design-tokens/src/dart.ts from ${DESIGN_TOKENS_PATH}. Do not edit; run \`npm run tokens:generate\`.`;
const SIX_DIGIT_HEX = /^#[0-9a-f]{6}$/i;
const DART_IDENTIFIER = /^[a-z][A-Za-z0-9]*$/;

function identifier(name: string): string {
  if (!DART_IDENTIFIER.test(name)) throw new Error(`design tokens: ${name} is not usable as a Dart name`);
  return name;
}

/** `#b4233d` to `Color(0xFFB4233D)`. */
function colorLiteral(name: string, value: string | undefined): string {
  if (value === undefined || !SIX_DIGIT_HEX.test(value)) throw new Error(`design tokens: colour ${name} is missing or not a six digit hex value`);
  return `Color(0xFF${value.slice(1).toUpperCase()})`;
}

function quote(text: string): string {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** `Segoe UI, Arial, sans-serif` to the first family and the fallbacks. */
function fontFamilies(css: string): { family: string; fallbacks: string[] } {
  const [family, ...fallbacks] = css.split(',').map((part) => part.trim()).filter((part) => part !== '');
  if (family === undefined) throw new Error('design tokens: font.family is empty');
  return { family, fallbacks };
}

function numeric(name: string, value: unknown): string {
  if (typeof value !== 'number' || !Number.isFinite(value)) throw new Error(`design tokens: ${name} is not a number`);
  return String(value);
}

function themeFunction(onPrimary: string): string {
  return `/// The minimum touch target of the platform: 44 points on Apple platforms, 48 dp elsewhere.
double machvonMinimumTouchTarget(TargetPlatform platform) {
  switch (platform) {
    case TargetPlatform.iOS:
    case TargetPlatform.macOS:
      return MachvonTouch.iosPoints;
    case TargetPlatform.android:
    case TargetPlatform.fuchsia:
    case TargetPlatform.linux:
    case TargetPlatform.windows:
      return MachvonTouch.androidDp;
  }
}

/// The Material theme of the mobile application, built only from the design tokens.
ThemeData machvonTheme({TargetPlatform? platform}) {
  final TargetPlatform target = platform ?? defaultTargetPlatform;
  final double touch = machvonMinimumTouchTarget(target);
  const ColorScheme scheme = ColorScheme.light(
    primary: MachvonColors.primary,
    onPrimary: ${onPrimary},
    secondary: MachvonColors.accent,
    onSecondary: MachvonColors.surface,
    error: MachvonColors.danger,
    onError: MachvonColors.surface,
    surface: MachvonColors.surface,
    onSurface: MachvonColors.ink,
    outline: MachvonColors.border,
  );
  const TextTheme text = TextTheme(
    bodyLarge: TextStyle(fontSize: MachvonFont.mobileBody, color: MachvonColors.ink),
    bodyMedium: TextStyle(fontSize: MachvonFont.mobileBody, color: MachvonColors.ink),
    bodySmall: TextStyle(fontSize: MachvonFont.navSecondary, color: MachvonColors.textSecondary),
    titleLarge: TextStyle(fontSize: MachvonFont.title, fontWeight: FontWeight.w600, color: MachvonColors.ink),
    labelLarge: TextStyle(fontSize: MachvonFont.mobileBody, fontWeight: FontWeight.w600),
  );
  final ButtonStyle buttonShape = ButtonStyle(
    minimumSize: WidgetStatePropertyAll<Size>(Size(touch, touch)),
    shape: WidgetStatePropertyAll<OutlinedBorder>(
      RoundedRectangleBorder(borderRadius: BorderRadius.circular(MachvonRadius.control)),
    ),
  );
  return ThemeData(
    useMaterial3: true,
    platform: target,
    colorScheme: scheme,
    scaffoldBackgroundColor: MachvonColors.background,
    fontFamily: MachvonFont.family,
    fontFamilyFallback: MachvonFont.fallbackFamilies,
    textTheme: text,
    materialTapTargetSize: MaterialTapTargetSize.padded,
    elevatedButtonTheme: ElevatedButtonThemeData(style: buttonShape),
    outlinedButtonTheme: OutlinedButtonThemeData(style: buttonShape),
    textButtonTheme: TextButtonThemeData(style: buttonShape),
  );
}`;
}

/**
 * Pure and deterministic: the Dart source of the mobile theme from the one design token file. It carries the
 * same tenant theme rules as the web (twelve colours, six text pairs, 4.5:1) so both clients refuse the same overlays.
 */
export function generateDart(json: DesignTokens): string {
  const tokens = buildTokens(json);
  const families = fontFamilies(tokens.font.family);
  const lines: string[] = [`// ${GENERATED_NOTICE}`, "import 'package:flutter/foundation.dart' show defaultTargetPlatform;", "import 'package:flutter/material.dart';", ''];

  lines.push('/// Colours of the design tokens.', 'abstract final class MachvonColors {');
  for (const [name, value] of Object.entries(tokens.color)) lines.push(`  static const Color ${identifier(name)} = ${colorLiteral(name, value)};`);
  lines.push('}', '');

  lines.push('/// Spacing steps in logical pixels.', 'abstract final class MachvonSpace {');
  for (const step of tokens.space) lines.push(`  static const double space${numeric('space', step)} = ${numeric('space', step)};`);
  lines.push('}', '');

  lines.push('/// Corner radii in logical pixels.', 'abstract final class MachvonRadius {');
  for (const [name, value] of Object.entries(tokens.radius)) lines.push(`  static const double ${identifier(name)} = ${numeric(name, value)};`);
  lines.push('}', '');

  lines.push(
    '/// Typography: the family with its fallbacks and the font sizes; the mobile body size is `mobileBody`.',
    'abstract final class MachvonFont {',
    `  static const String family = ${quote(families.family)};`,
    `  static const List<String> fallbackFamilies = <String>[${families.fallbacks.map(quote).join(', ')}];`,
    `  static const double body = ${numeric('font.body', tokens.font.body)};`,
    `  static const double title = ${numeric('font.title', tokens.font.title)};`,
    `  static const double mobileBody = ${numeric('font.mobileBody', tokens.font.mobileBody)};`,
    `  static const double navPrimary = ${numeric('font.navPrimary', tokens.font.navPrimary)};`,
    `  static const double navSecondary = ${numeric('font.navSecondary', tokens.font.navSecondary)};`,
    '}',
    '',
    '/// Minimum touch targets of the native platforms.',
    'abstract final class MachvonTouch {',
    `  static const double iosPoints = ${numeric('touch.ios_pt', tokens.touch.ios_pt)};`,
    `  static const double androidDp = ${numeric('touch.android_dp', tokens.touch.android_dp)};`,
    '}',
    '',
    '/// The reference viewport of the mobile design.',
    'abstract final class MachvonViewport {',
    `  static const double width = ${numeric('viewport.mobile', tokens.viewport.mobile[0])};`,
    `  static const double height = ${numeric('viewport.mobile', tokens.viewport.mobile[1])};`,
    '}',
    '',
  );

  lines.push(
    '/// Minimum contrast of every text/background pair of a tenant theme (WCAG AA for normal text).',
    `const double kMinTextContrast = ${MIN_TEXT_CONTRAST};`,
    '',
    '/// The colours a tenant theme overlay may set.',
    `const List<String> kThemeColorKeys = <String>[${THEME_COLOR_KEYS.map(quote).join(', ')}];`,
    '',
    '/// The base tenant theme: the value of every overridable colour before an overlay.',
    'const Map<String, Color> kBaseTenantTheme = <String, Color>{',
  );
  for (const key of THEME_COLOR_KEYS) lines.push(`  ${quote(key)}: ${colorLiteral(key, tokens.tenantTheme[key])},`);
  lines.push('};', '');

  lines.push(
    '/// A text colour and the background it is drawn on, both named by theme colour key.',
    'class ContrastPairSpec {',
    '  const ContrastPairSpec(this.id, this.foreground, this.background);',
    '',
    '  final String id;',
    '  final String foreground;',
    '  final String background;',
    '}',
    '',
    'const List<ContrastPairSpec> kContrastPairs = <ContrastPairSpec>[',
  );
  for (const pair of CONTRAST_PAIRS) lines.push(`  ContrastPairSpec(${quote(pair.id)}, ${quote(pair.foreground)}, ${quote(pair.background)}),`);
  lines.push('];', '', themeFunction(colorLiteral('primaryText', tokens.tenantTheme.primaryText)), '');
  return lines.join('\n');
}
