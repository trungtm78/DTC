import { DART_OUTPUT_PATH, generateDart } from '../src/dart.ts';
import { buildTokens } from '../src/generate.ts';
import { CONTRAST_PAIRS, MIN_TEXT_CONTRAST, THEME_COLOR_KEYS } from '../src/theme-rules.ts';
import { realDesignTokens } from './support.ts';

describe('generateDart', () => {
  const json = realDesignTokens();
  const dart = generateDart(json);

  it('is deterministic: two runs give identical text', () => {
    expect(generateDart(json)).toBe(dart);
  });

  it('writes plain ASCII English only, so no display text of the design lands in a source file', () => {
    expect(dart).toMatch(/^[\n -~]*$/);
    expect(dart).not.toContain(json.displayName);
    expect(dart.startsWith('// Generated by packages/design-tokens/src/dart.ts')).toBe(true);
    expect(dart).toContain('Do not edit');
  });

  it('writes every colour token as an upper-case 0xFFRRGGBB literal', () => {
    for (const [name, value] of Object.entries(json.color)) {
      expect(dart).toContain(`static const Color ${name} = Color(0xFF${value.slice(1).toUpperCase()});`);
    }
    expect(dart).toContain('static const Color primary = Color(0xFFB4233D);');
  });

  it('writes the spacing steps, the radii and the font sizes with the mobile body size', () => {
    for (const step of json.space) expect(dart).toContain(`static const double space${step} = ${step};`);
    for (const [name, value] of Object.entries(json.radius)) expect(dart).toContain(`static const double ${name} = ${value};`);
    expect(dart).toContain('static const double mobileBody = 16;');
    expect(dart).toContain('static const double title = 27;');
    expect(dart).toContain("static const String family = 'Segoe UI';");
    expect(dart).toContain("static const List<String> fallbackFamilies = <String>['Arial', 'sans-serif'];");
  });

  it('writes the touch target constants for iOS and Android', () => {
    expect(dart).toContain('static const double iosPoints = 44;');
    expect(dart).toContain('static const double androidDp = 48;');
  });

  it('writes the tenant theme rules of the web: twelve keys, the base values, six pairs and the 4.5 minimum', () => {
    expect(dart).toContain(`const double kMinTextContrast = ${MIN_TEXT_CONTRAST};`);
    for (const key of THEME_COLOR_KEYS) expect(dart).toContain(`'${key}': Color(0xFF`);
    for (const pair of CONTRAST_PAIRS) expect(dart).toContain(`ContrastPairSpec('${pair.id}', '${pair.foreground}', '${pair.background}')`);
    const base = buildTokens(json).tenantTheme;
    expect(dart).toContain(`'primary': Color(0xFF${base.primary.slice(1)})`);
    expect(dart).toContain(`'selectedText': Color(0xFF${base.selectedText.slice(1).toUpperCase()})`);
  });

  it('builds the theme from the generated constants', () => {
    expect(dart).toContain('ThemeData machvonTheme({TargetPlatform? platform})');
    expect(dart).toContain('double machvonMinimumTouchTarget(TargetPlatform platform)');
    expect(dart).toContain('fontSize: MachvonFont.mobileBody');
    expect(dart).toContain('fontSize: MachvonFont.title');
  });

  it('knows where it is written', () => {
    expect(DART_OUTPUT_PATH).toBe('packages/mobile-tokens/lib/machvon_theme.generated.dart');
  });

  it('refuses a design token file without a required value', () => {
    const broken = { ...json, color: { ...json.color } };
    delete (broken.color as Record<string, string>).primary;
    expect(() => generateDart(broken)).toThrow(/primary/);
  });

  it('refuses a colour that is not a six digit hex value', () => {
    expect(() => generateDart({ ...json, color: { ...json.color, primary: 'red' } })).toThrow(/primary/);
  });
});
