import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { APP_ROLE, MACHVON_ROLES, OWNER_ROLE } from './roles.ts';

export interface GeneratedMigration {
  name: string;
  sql: string;
}

export const SCHEMA_SOURCE_PATH = 'Design/MACHVON_Design/03_Engineering/schema_reference.sql';
export const MIGRATIONS_DIR = 'db/migrations';
export const PRIVILEGED_MARKER = '-- migrate: privileged';

const ROLES_MIGRATION = 'V001__roles_and_grants';
const SCHEMA_MIGRATION = 'V002__schema';
const SCHEMA_NAME = 'machvon';
// The design names this table audit_event (the design prose still says audit_entry).
const AUDIT_TABLE = 'audit_event';

function normalizeEol(text: string): string {
  return text.replace(/\r\n/g, '\n');
}

function header(digest: string, name: string): string {
  return `-- Generated by packages/db/src/generate-migrations.ts (${name}) from ${SCHEMA_SOURCE_PATH} sha256:${digest}. Do not edit; run \`npm run db:generate\`.`;
}

function rolesAndGrants(): string {
  const quoted = MACHVON_ROLES.map((role) => `'${role}'`).join(', ');
  const others = MACHVON_ROLES.filter((role) => role !== OWNER_ROLE);
  return [
    PRIVILEGED_MARKER,
    '-- Roles carry no password: deployment sets credentials. Runs as the privileged connection, not as the owner.',
    'DO $roles$',
    'DECLARE role_name text;',
    'BEGIN',
    `  FOREACH role_name IN ARRAY ARRAY[${quoted}] LOOP`,
    '    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN',
    "      EXECUTE format('CREATE ROLE %I LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE', role_name);",
    '    END IF;',
    '  END LOOP;',
    'END',
    '$roles$;',
    '',
    '-- The owner runs migrations: it needs CREATE on the database for the schema and trusted extensions.',
    'DO $database$',
    'BEGIN',
    `  EXECUTE format('GRANT CONNECT, CREATE ON DATABASE %I TO ${OWNER_ROLE}', current_database());`,
    `  EXECUTE format('GRANT CONNECT ON DATABASE %I TO ${others.join(', ')}', current_database());`,
    'END',
    '$database$;',
    '',
    `CREATE SCHEMA IF NOT EXISTS ${SCHEMA_NAME} AUTHORIZATION ${OWNER_ROLE};`,
    `ALTER SCHEMA ${SCHEMA_NAME} OWNER TO ${OWNER_ROLE};`,
    `GRANT USAGE ON SCHEMA ${SCHEMA_NAME} TO ${others.join(', ')};`,
    '',
    `ALTER DEFAULT PRIVILEGES FOR ROLE ${OWNER_ROLE} IN SCHEMA ${SCHEMA_NAME} GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_ROLE};`,
    `ALTER DEFAULT PRIVILEGES FOR ROLE ${OWNER_ROLE} IN SCHEMA ${SCHEMA_NAME} GRANT USAGE, SELECT ON SEQUENCES TO ${APP_ROLE};`,
    '',
  ].join('\n');
}

// The audit table does not exist before V002, and default privileges grant DML on every new table,
// so the append-only restriction is applied right after the design schema creates the table.
function postSchemaGrants(): string {
  return [
    '',
    '-- BEGIN generated: post-schema grants',
    `REVOKE UPDATE, DELETE ON ${SCHEMA_NAME}.${AUDIT_TABLE} FROM ${APP_ROLE};`,
    '-- END generated: post-schema grants',
    '',
  ].join('\n');
}

/**
 * Pure and deterministic: V001 (roles and grants, generator-owned template) and V002 (the design SQL
 * verbatim plus a marked post-schema grant block). Line endings of the source never change the output.
 */
export function generateMigrations(schemaSql: string): GeneratedMigration[] {
  const source = normalizeEol(schemaSql);
  const digest = createHash('sha256').update(source).digest('hex');
  return [
    { name: ROLES_MIGRATION, sql: `${header(digest, ROLES_MIGRATION)}\n${rolesAndGrants()}` },
    { name: SCHEMA_MIGRATION, sql: `${header(digest, SCHEMA_MIGRATION)}\n${source}${postSchemaGrants()}` },
  ];
}

async function generateFor(root: string): Promise<GeneratedMigration[]> {
  return generateMigrations(await readFile(join(root, SCHEMA_SOURCE_PATH), 'utf8'));
}

/** Writes the generated migrations (LF line endings) under db/migrations and returns the file names. */
export async function writeGenerated(root: string): Promise<string[]> {
  const migrations = await generateFor(root);
  const directory = join(root, MIGRATIONS_DIR);
  await mkdir(directory, { recursive: true });
  const files: string[] = [];
  for (const migration of migrations) {
    const file = `${migration.name}.sql`;
    await writeFile(join(directory, file), migration.sql);
    files.push(file);
  }
  return files;
}

async function readCommitted(path: string): Promise<string | undefined> {
  try {
    return normalizeEol(await readFile(path, 'utf8'));
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
    throw error;
  }
}

/** Throws when a committed migration is missing or differs from regeneration. */
export async function checkGenerated(root: string): Promise<void> {
  const stale: string[] = [];
  for (const migration of await generateFor(root)) {
    const file = `${migration.name}.sql`;
    const committed = await readCommitted(join(root, MIGRATIONS_DIR, file));
    if (committed !== migration.sql) stale.push(file);
  }
  if (stale.length > 0) {
    throw new Error(`Generated migrations are out of date: ${stale.join(', ')}. Run \`npm run db:generate\`.`);
  }
}

/** Reads the committed migration files in version order, with LF line endings. */
export async function loadCommittedMigrations(root: string): Promise<GeneratedMigration[]> {
  const names = (await readdir(join(root, MIGRATIONS_DIR))).filter((file) => file.endsWith('.sql')).sort();
  const migrations: GeneratedMigration[] = [];
  for (const file of names) {
    migrations.push({ name: file.slice(0, -'.sql'.length), sql: normalizeEol(await readFile(join(root, MIGRATIONS_DIR, file), 'utf8')) });
  }
  return migrations;
}
