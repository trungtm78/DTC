import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import type { OpenAPI3 } from 'openapi-typescript';
import { lintOpenApi } from './lint-openapi.ts';
import { listOperations } from './openapi-document.ts';
import type { OpenApiDocument, OpenApiOperation } from './openapi-document.ts';

export const PERMISSIONS_FILE = 'permissions.generated.ts';
export const TYPES_FILE = 'types.generated.ts';
export const OPERATIONS_FILE = 'operations.generated.ts';

const GENERATED_BANNER = '// Generated by packages/contracts/src/generate.ts from openapi.json. Do not edit; run `npm run contracts:generate`.\n';

// Maps operationId to its x-permission value.
export function generatePermissions(doc: OpenApiDocument): Record<string, string> {
  const permissions: Record<string, string> = {};
  for (const { id, operation } of listOperations(doc)) {
    const permission = operation['x-permission'];
    if (typeof permission !== 'string' || permission === '') throw new Error(`${id} has no x-permission`);
    if (Object.hasOwn(permissions, id)) throw new Error(`Duplicate operationId: ${id}`);
    permissions[id] = permission;
  }
  return permissions;
}

const STEP_UP_LEVELS: readonly string[] = ['aal2'];
const PLANE_NAMES: readonly string[] = ['tenant', 'control', 'internal', 'edge'];
const DEFAULT_PLANE = 'tenant';

// Maps operationId to its x-step-up level; only operations that require step-up appear.
export function generateStepUp(doc: OpenApiDocument): Record<string, string> {
  const stepUp: Record<string, string> = {};
  for (const { id, operation } of listOperations(doc)) {
    const level = operation['x-step-up'];
    if (level === undefined) continue;
    if (typeof level !== 'string' || !STEP_UP_LEVELS.includes(level)) throw new Error(`${id} has an unsupported x-step-up`);
    stepUp[id] = level;
  }
  return stepUp;
}

// Maps every operationId to its x-plane; an operation without one belongs to the tenant plane.
export function generatePlanes(doc: OpenApiDocument): Record<string, string> {
  const planes: Record<string, string> = {};
  for (const { id, operation } of listOperations(doc)) {
    const plane = operation['x-plane'] ?? DEFAULT_PLANE;
    if (typeof plane !== 'string' || !PLANE_NAMES.includes(plane)) throw new Error(`${id} has an unsupported x-plane`);
    planes[id] = plane;
  }
  return planes;
}

export interface OperationDescriptor {
  method: string;
  path: string;
  /** The operation declares an If-Match header parameter: the caller must send the version it saw. */
  versioned: boolean;
  stepUp: string | null;
  permission: string;
}

const IF_MATCH_HEADER = 'if-match';
const PARAMETER_REF_PREFIX = '#/components/parameters/';

// Names of the parameters of an operation, following references into components.parameters.
function parameterNames(operation: OpenApiOperation, doc: OpenApiDocument): string[] {
  const shared = (doc.components?.parameters ?? {}) as Record<string, { name?: unknown }>;
  const parameters = Array.isArray(operation.parameters) ? (operation.parameters as Array<{ name?: unknown; $ref?: unknown }>) : [];
  const names: string[] = [];
  for (const parameter of parameters) {
    const resolved = typeof parameter.$ref === 'string' && parameter.$ref.startsWith(PARAMETER_REF_PREFIX)
      ? shared[parameter.$ref.slice(PARAMETER_REF_PREFIX.length)]
      : parameter;
    if (typeof resolved?.name === 'string') names.push(resolved.name);
  }
  return names;
}

// Describes every operation for clients: how to call it and which header protocol it follows.
export function generateOperations(doc: OpenApiDocument): Record<string, OperationDescriptor> {
  const operations: Record<string, OperationDescriptor> = {};
  const permissions = generatePermissions(doc);
  const stepUp = generateStepUp(doc);
  for (const { id, method, path, operation } of listOperations(doc)) {
    if (Object.hasOwn(operations, id)) throw new Error(`Duplicate operationId: ${id}`);
    operations[id] = {
      method,
      path,
      versioned: parameterNames(operation, doc).some((name) => name.toLowerCase() === IF_MATCH_HEADER),
      stepUp: stepUp[id] ?? null,
      permission: permissions[id] ?? '',
    };
  }
  return operations;
}

export function renderOperationsModule(operations: Record<string, OperationDescriptor>): string {
  const lines = Object.keys(operations)
    .sort()
    .map((operationId) => {
      const descriptor = operations[operationId] as OperationDescriptor;
      const fields = [
        `method: ${JSON.stringify(descriptor.method)}`,
        `path: ${JSON.stringify(descriptor.path)}`,
        `versioned: ${descriptor.versioned}`,
        `stepUp: ${JSON.stringify(descriptor.stepUp)}`,
        `permission: ${JSON.stringify(descriptor.permission)}`,
      ];
      return `  ${JSON.stringify(operationId)}: { ${fields.join(', ')} },`;
    });
  return [
    GENERATED_BANNER.trimEnd(),
    'export const OPERATIONS = {',
    ...lines,
    '} as const;',
    '',
    'export type OperationName = keyof typeof OPERATIONS;',
    '',
  ].join('\n');
}

function renderTable(name: string, table: Record<string, string>): string[] {
  const lines = Object.keys(table)
    .sort()
    .map((operationId) => `  ${JSON.stringify(operationId)}: ${JSON.stringify(table[operationId])},`);
  return [`export const ${name} = {`, ...lines, '} as const;', ''];
}

export function renderPermissionsModule(
  permissions: Record<string, string>,
  stepUp: Record<string, string> = {},
  planes: Record<string, string> = {},
): string {
  return [
    GENERATED_BANNER.trimEnd(),
    ...renderTable('PERMISSIONS', permissions),
    'export type OperationId = keyof typeof PERMISSIONS;',
    '',
    ...renderTable('STEP_UP', stepUp),
    ...renderTable('PLANES', planes),
  ].join('\n');
}

// openapi-typescript is ESM only, so it is loaded lazily with a dynamic import.
export async function generateTypes(doc: OpenApiDocument): Promise<string> {
  const { default: openapiTS, astToString } = await import('openapi-typescript');
  const ast = await openapiTS(doc as unknown as OpenAPI3);
  return `${GENERATED_BANNER}${astToString(ast)}`.replace(/\r\n/g, '\n').replace(/\n*$/, '\n');
}

export interface Io {
  log: (line: string) => void;
}

const USAGE = 'Usage: generate.ts --spec <openapi.json> --out <directory> [--check]';

const stdoutIo: Io = { log: (line) => process.stdout.write(`${line}\n`) };

function normalizeEol(text: string): string {
  return text.replace(/\r\n/g, '\n');
}

// Generates the committed outputs, or with --check compares them and fails on any difference.
// Exit codes: 0 ok, 1 lint or drift failure, 2 usage error.
export async function main(argv: string[], io: Io = stdoutIo): Promise<number> {
  const { values } = parseArgs({
    args: argv,
    options: { spec: { type: 'string' }, out: { type: 'string' }, check: { type: 'boolean', default: false } },
  });
  if (values.spec === undefined || values.out === undefined) {
    io.log(`--spec and --out are required. ${USAGE}`);
    return 2;
  }
  const doc = JSON.parse(readFileSync(resolve(values.spec), 'utf8')) as OpenApiDocument;
  const findings = lintOpenApi(doc);
  for (const finding of findings) io.log(`${finding.rule}: ${finding.operationId}`);
  if (findings.length > 0) return 1;

  const outputs: Record<string, string> = {
    [PERMISSIONS_FILE]: renderPermissionsModule(generatePermissions(doc), generateStepUp(doc), generatePlanes(doc)),
    [OPERATIONS_FILE]: renderOperationsModule(generateOperations(doc)),
    [TYPES_FILE]: await generateTypes(doc),
  };
  const outDir = resolve(values.out);
  if (!values.check) {
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of Object.entries(outputs)) writeFileSync(join(outDir, name), content);
    return 0;
  }
  const stale = Object.entries(outputs)
    .filter(([name, content]) => {
      const path = join(outDir, name);
      return !existsSync(path) || normalizeEol(readFileSync(path, 'utf8')) !== content;
    })
    .map(([name]) => name);
  for (const name of stale) io.log(`${name} is out of date; run \`npm run contracts:generate\``);
  return stale.length === 0 ? 0 : 1;
}

// Runs only when started as a script (node src/generate.ts), never when imported by tests.
if (process.argv[1] !== undefined && /[\\/]generate\.ts$/.test(process.argv[1])) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (error: unknown) => {
      process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
      process.exitCode = 1;
    },
  );
}
