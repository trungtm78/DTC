import { generateOperations } from './generate.ts';
import { generateRequestSchemas } from './generate-validators.ts';
import { listOperations } from './openapi-document.ts';
import type { OpenApiDocument } from './openapi-document.ts';
import type { Schema } from './validation.ts';

export const DART_OPERATIONS_FILE = 'operations.generated.dart';
export const DART_REQUESTS_FILE = 'requests.generated.dart';
export const DART_COMMANDS_FILE = 'commands.generated.dart';

export interface DartFiles {
  operations: string;
  requests: string;
  commands: string;
}

const BANNER = '// Generated by packages/contracts/src/generate-dart.ts from openapi.json. Do not edit; run `npm run contracts:generate`.';
const REF_PREFIX = '#/components/schemas/';
const HTTP_READ = 'get';
const RESERVED = new Set(
  (
    'abstract as assert async await base break case catch class const continue covariant default deferred do dynamic else enum ' +
    'export extends extension external factory false final finally for Function get hide if implements import in interface is ' +
    'late library mixin new null of on operator part required rethrow return sealed set show static super switch sync this ' +
    'throw true try type typedef var void when while with yield hashCode runtimeType toString noSuchMethod toJson'
  ).split(' '),
);
// Names the generated client methods already use for their own parameters.
const METHOD_PARAMETERS = new Set(['body', 'ifMatchVersion', 'attempt', 'query']);

type Node = Record<string, unknown>;

function asNode(value: unknown): Node | undefined {
  return typeof value === 'object' && value !== null && !Array.isArray(value) ? (value as Node) : undefined;
}

function words(text: string): string[] {
  return text.split(/[^A-Za-z0-9]+/).filter((word) => word !== '');
}

function camel(text: string): string {
  const [first = '', ...rest] = words(text);
  const joined = first.charAt(0).toLowerCase() + first.slice(1) + rest.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join('');
  return /^[0-9]/.test(joined) ? `n${joined}` : joined;
}

function pascal(text: string): string {
  const name = words(text).map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join('');
  return /^[0-9]/.test(name) ? `N${name}` : name;
}

function safe(name: string): string {
  return RESERVED.has(name) ? `${name}_` : name;
}

function quote(text: string): string {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
}

function classNameOf(key: string): string {
  return key.startsWith('operation:') ? `${pascal(key.slice('operation:'.length))}Request` : pascal(key);
}

interface Model {
  name: string;
  required: Set<string>;
  properties: Array<[wire: string, schema: Node]>;
}

class Generator {
  private readonly schemas: Record<string, Schema>;
  private readonly models = new Map<string, Model>();

  constructor(schemas: Record<string, Schema>) {
    this.schemas = schemas;
  }

  /** The object models of every request schema, nested inline objects included; sorted by class name. */
  build(): Model[] {
    for (const [key, schema] of Object.entries(this.schemas)) {
      if (this.isModel(schema as Node)) this.register(classNameOf(key), schema as Node);
    }
    return [...this.models.values()].sort((a, b) => a.name.localeCompare(b.name));
  }

  /** Dart type of a body schema (a class, a map or a plain object). */
  bodyType(key: string): string {
    return this.typeOf(this.schemas[key] as Node, classNameOf(key), '');
  }

  private isModel(schema: Node): boolean {
    return schema.type === 'object' && asNode(schema.properties) !== undefined && Object.keys(asNode(schema.properties) as Node).length > 0;
  }

  private register(name: string, schema: Node): void {
    if (this.models.has(name)) throw new Error(`two request classes would be named ${name}`);
    const properties = Object.entries(asNode(schema.properties) as Node).map(([wire, property]) => [wire, asNode(property) ?? {}] as [string, Node]);
    const model: Model = { name, required: new Set(Array.isArray(schema.required) ? schema.required.map(String) : []), properties };
    this.models.set(name, model);
    for (const [wire, property] of properties) this.typeOf(property, name, wire);
  }

  /** Dart type of a schema; an inline object with properties becomes a class named after its owner and field. */
  typeOf(schema: Node, owner: string, field: string): string {
    const nullable = schema.nullable === true ? '?' : '';
    const ref = typeof schema.$ref === 'string' && schema.$ref.startsWith(REF_PREFIX) ? schema.$ref.slice(REF_PREFIX.length) : undefined;
    if (ref !== undefined) {
      const target = asNode(this.schemas[ref]);
      if (target === undefined) throw new Error(`request schema ${ref} is missing`);
      return `${this.isModel(target) ? classNameOf(ref) : this.typeOf(target, classNameOf(ref), '')}${nullable}`;
    }
    if (Array.isArray(schema.oneOf)) return `Object${nullable}`;
    switch (schema.type) {
      case 'string':
        return `String${nullable}`;
      case 'integer':
        return `int${nullable}`;
      case 'number':
        return `num${nullable}`;
      case 'boolean':
        return `bool${nullable}`;
      case 'array': {
        const items = asNode(schema.items);
        const inner = items === undefined ? 'Object?' : this.typeOf(items, owner, `${field}Item`);
        return `List<${inner}>${nullable}`;
      }
      case 'object': {
        if (this.isModel(schema)) {
          const name = `${owner}${pascal(field)}`;
          if (!this.models.has(name)) this.register(name, schema);
          return `${name}${nullable}`;
        }
        const additional = asNode(schema.additionalProperties);
        return `Map<String, ${additional === undefined ? 'Object?' : this.typeOf(additional, owner, `${field}Value`)}>${nullable}`;
      }
      default:
        return `Object?`;
    }
  }
}

function renderModel(model: Model, generator: Generator): string {
  const used = new Map<string, string>();
  const fields = model.properties.map(([wire, schema]) => {
    const name = safe(camel(wire));
    const clash = used.get(name);
    if (clash !== undefined) throw new Error(`${model.name}: properties ${clash} and ${wire} would both be named ${name}`);
    used.set(name, wire);
    const required = model.required.has(wire);
    const base = generator.typeOf(schema, model.name, wire);
    const type = required || base.endsWith('?') ? base : `${base}?`;
    return { wire, name, required, type };
  });
  const ordered = [...fields.filter((field) => field.required), ...fields.filter((field) => !field.required)];
  return [
    `final class ${model.name} implements RequestModel {`,
    `  const ${model.name}({`,
    ...ordered.map((field) => `    ${field.required ? 'required ' : ''}this.${field.name},`),
    '  });',
    '',
    ...fields.map((field) => `  final ${field.type} ${field.name};`),
    '',
    '  @override',
    '  Map<String, Object?> toJson() => <String, Object?>{',
    ...fields.map((field) => (field.required ? `        ${quote(field.wire)}: ${field.name},` : `        if (${field.name} != null) ${quote(field.wire)}: ${field.name},`)),
    '      };',
    '}',
    '',
  ].join('\n');
}

function pathParameters(path: string): Array<{ wire: string; name: string }> {
  return [...path.matchAll(/\{([^{}/]+)\}/g)].map((match) => {
    const wire = match[1] as string;
    const name = safe(camel(wire));
    if (METHOD_PARAMETERS.has(name)) throw new Error(`path parameter ${wire} would collide with a client parameter`);
    return { wire, name };
  });
}

/** Dart sources for the mobile client: operation descriptors, typed request classes and one typed method per operation. */
export function generateDart(doc: OpenApiDocument): DartFiles {
  const descriptors = generateOperations(doc);
  const { bodies, schemas } = generateRequestSchemas(doc);
  const generator = new Generator(schemas);
  const models = generator.build();

  const operationIds = Object.keys(descriptors).sort();
  const operations = [
    BANNER,
    "import 'operation_descriptor.dart';",
    '',
    'const Map<String, OperationDescriptor> operationDescriptors = <String, OperationDescriptor>{',
    ...operationIds.map((id) => {
      const descriptor = descriptors[id] as (typeof descriptors)[string];
      const stepUp = descriptor.stepUp === null ? 'null' : quote(descriptor.stepUp);
      return `  ${quote(id)}: OperationDescriptor(method: ${quote(descriptor.method.toUpperCase())}, path: ${quote(descriptor.path)}, versioned: ${descriptor.versioned}, stepUp: ${stepUp}, permission: ${quote(descriptor.permission)}),`;
    }),
    '};',
    '',
  ].join('\n');

  const requests = [BANNER, "import 'request_model.dart';", '', ...models.map((model) => renderModel(model, generator))].join('\n');

  const hasBody = new Map(listOperations(doc).map((entry) => [entry.id, (entry.operation as Node).requestBody !== undefined]));
  const methodNames = new Map<string, string>();
  const methods: string[] = [];
  for (const id of operationIds) {
    const descriptor = descriptors[id] as (typeof descriptors)[string];
    const bodyKey = bodies[id];
    // A body that is not offered as JSON (a file upload) has no typed method.
    if (bodyKey === undefined && hasBody.get(id) === true) continue;
    const name = safe(camel(id));
    const clash = methodNames.get(name);
    if (clash !== undefined) throw new Error(`operations ${clash} and ${id} would both be named ${name}`);
    methodNames.set(name, id);

    const path = pathParameters(descriptor.path);
    const pathMap = path.length === 0 ? '' : `path: <String, Object?>{${path.map((parameter) => `${quote(parameter.wire)}: ${parameter.name}`).join(', ')}}, `;
    const pathNamed = path.map((parameter) => `required String ${parameter.name}`);
    if (descriptor.method === HTTP_READ) {
      const named = [...pathNamed, 'Map<String, Object?>? query'];
      methods.push(`  Future<Object?> ${name}({${named.join(', ')}}) =>\n      execute(${quote(id)}, ${pathMap}query: query);`);
      continue;
    }
    const named = [...pathNamed, ...(descriptor.versioned ? ['required int ifMatchVersion'] : []), 'CommandAttempt? attempt'];
    const positional = bodyKey === undefined ? '' : `${generator.bodyType(bodyKey)} body, `;
    const forward = `${bodyKey === undefined ? '' : 'body: body, '}${descriptor.versioned ? 'ifMatchVersion: ifMatchVersion, ' : ''}attempt: attempt`;
    methods.push(`  Future<Object?> ${name}(${positional}{${named.join(', ')}}) =>\n      execute(${quote(id)}, ${pathMap}${forward});`);
  }
  const commands = [
    BANNER,
    "import 'client.dart';",
    "import 'command_attempt.dart';",
    "import 'requests.generated.dart';",
    '',
    'extension MachvonOperations on MachvonApiClient {',
    methods.join('\n\n'),
    '}',
    '',
  ].join('\n');

  return { operations, requests, commands };
}
