import { listOperations } from './openapi-document.ts';
import type { OpenApiDocument } from './openapi-document.ts';
import type { Schema } from './validation.ts';

export const REQUEST_SCHEMAS_FILE = 'request-schemas.generated.ts';

const GENERATED_BANNER = '// Generated by packages/contracts/src/generate.ts from openapi.json. Do not edit; run `npm run contracts:generate`.';
const JSON_CONTENT_TYPE = 'application/json';
const REF_PREFIX = '#/components/schemas/';

// Keywords the runtime validator enforces; every other validation keyword is refused so no rule is silently skipped.
const ENFORCED = new Set([
  '$ref',
  'type',
  'nullable',
  'properties',
  'required',
  'additionalProperties',
  'items',
  'oneOf',
  'enum',
  'pattern',
  'format',
  'contentEncoding',
  'minLength',
  'maxLength',
  'minimum',
  'maximum',
  'minItems',
  'maxItems',
]);
// Annotations carry no validation rule.
const ANNOTATIONS = new Set(['description', 'title', 'example', 'examples', 'default', 'deprecated', 'readOnly', 'writeOnly', 'externalDocs']);

export interface RequestSchemas {
  /** operationId to the key of its request body schema in `schemas`. */
  bodies: Record<string, string>;
  /** Component schemas (and inline body schemas, keyed `operation:<operationId>`) reachable from the bodies. */
  schemas: Record<string, Schema>;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function strip(value: unknown, where: string, referenced: Set<string>): Schema {
  if (!isRecord(value)) throw new Error(`request schema ${where} is not an object`);
  const result: Record<string, unknown> = {};
  for (const [keyword, member] of Object.entries(value)) {
    if (ANNOTATIONS.has(keyword) || keyword.startsWith('x-')) continue;
    if (!ENFORCED.has(keyword)) throw new Error(`unsupported keyword ${keyword} in request schema ${where}`);
    if (keyword === '$ref') {
      if (typeof member !== 'string' || !member.startsWith(REF_PREFIX)) throw new Error(`unsupported reference in request schema ${where}`);
      referenced.add(member.slice(REF_PREFIX.length));
      result[keyword] = member;
    } else if (keyword === 'properties') {
      if (!isRecord(member)) throw new Error(`request schema ${where} has invalid properties`);
      result[keyword] = Object.fromEntries(Object.entries(member).map(([name, property]) => [name, strip(property, `${where}.${name}`, referenced)]));
    } else if (keyword === 'items') {
      result[keyword] = strip(member, `${where}[]`, referenced);
    } else if (keyword === 'additionalProperties') {
      result[keyword] = typeof member === 'boolean' ? member : strip(member, `${where}.*`, referenced);
    } else if (keyword === 'oneOf') {
      if (!Array.isArray(member)) throw new Error(`request schema ${where} has invalid oneOf`);
      result[keyword] = member.map((alternative, index) => strip(alternative, `${where}|${index}`, referenced));
    } else {
      result[keyword] = member;
    }
  }
  return result as Schema;
}

/** The request body schemas of every operation with a JSON body, closed under `$ref`, reduced to enforceable keywords. */
export function generateRequestSchemas(doc: OpenApiDocument): RequestSchemas {
  const components = (doc.components?.schemas ?? {}) as Record<string, unknown>;
  const bodies: Record<string, string> = {};
  const schemas: Record<string, Schema> = {};
  const pending = new Set<string>();

  for (const { id, operation } of listOperations(doc)) {
    const body = operation.requestBody;
    const content = isRecord(body) && isRecord(body.content) ? body.content[JSON_CONTENT_TYPE] : undefined;
    if (!isRecord(content) || content.schema === undefined) continue;
    const root = content.schema;
    if (isRecord(root) && typeof root.$ref === 'string' && root.$ref.startsWith(REF_PREFIX) && Object.keys(root).length === 1) {
      const name = root.$ref.slice(REF_PREFIX.length);
      bodies[id] = name;
      pending.add(name);
    } else {
      const key = `operation:${id}`;
      const referenced = new Set<string>();
      schemas[key] = strip(root, key, referenced);
      bodies[id] = key;
      for (const name of referenced) pending.add(name);
    }
  }

  const done = new Set<string>();
  while (pending.size > 0) {
    const [name] = pending;
    pending.delete(name as string);
    if (done.has(name as string)) continue;
    done.add(name as string);
    const source = components[name as string];
    if (source === undefined) throw new Error(`request schema ${name as string} is not defined in components.schemas`);
    const referenced = new Set<string>();
    schemas[name as string] = strip(source, name as string, referenced);
    for (const next of referenced) if (!done.has(next)) pending.add(next);
  }
  return { bodies: sortedObject(bodies), schemas: sortedObject(schemas) };
}

function sortedObject<T>(table: Record<string, T>): Record<string, T> {
  return Object.fromEntries(Object.keys(table).sort().map((key) => [key, table[key] as T]));
}

// JSON with every non-ASCII character escaped, so the generated source holds no accented letters.
function asciiJson(value: unknown): string {
  return JSON.stringify(value).replace(/\P{ASCII}/gu, (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`);
}

export function renderRequestSchemasModule({ bodies, schemas }: RequestSchemas): string {
  return [
    GENERATED_BANNER,
    "import type { Schema } from './validation.ts';",
    '',
    'export const REQUEST_SCHEMAS: Readonly<Record<string, Schema>> = {',
    ...Object.entries(schemas).map(([name, schema]) => `  ${asciiJson(name)}: ${asciiJson(schema)},`),
    '};',
    '',
    'export const REQUEST_BODIES: Readonly<Record<string, string>> = {',
    ...Object.entries(bodies).map(([operationId, name]) => `  ${asciiJson(operationId)}: ${asciiJson(name)},`),
    '};',
    '',
  ].join('\n');
}
