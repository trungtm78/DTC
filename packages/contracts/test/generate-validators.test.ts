import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { REQUEST_SCHEMAS_FILE, generateRequestSchemas, renderRequestSchemasModule } from '../src/generate-validators';
import { main } from '../src/generate';
import { listOperations } from '../src/openapi-document';
import { REQUEST_BODIES, REQUEST_SCHEMAS } from '../src/request-schemas.generated';
import { requestSchemaOf, validateRequestBody } from '../src/request-validation';
import { documentWith, loadRealDocument } from './fixtures';

const GENERATED_DIR = resolve(__dirname, '..', 'src');
const json = (schema: unknown): Record<string, unknown> => ({ content: { 'application/json': { schema } } });

const small = documentWith(
  {
    '/things': {
      post: {
        operationId: 'create_thing',
        requestBody: json({ $ref: '#/components/schemas/ThingCreate' }),
        responses: {},
      },
      put: {
        operationId: 'inline_thing',
        requestBody: json({ type: 'object', additionalProperties: false, properties: { n: { type: 'integer', description: 'ignored' } } }),
        responses: {},
      },
      delete: { operationId: 'delete_thing', responses: {} },
    },
    '/upload': {
      post: { operationId: 'upload_thing', requestBody: { content: { 'multipart/form-data': { schema: { type: 'object' } } } }, responses: {} },
    },
    '/things/{id}': { get: { operationId: 'get_thing', responses: {} } },
  },
  {
    ThingCreate: {
      type: 'object',
      description: 'A thing',
      additionalProperties: false,
      required: ['name'],
      properties: { name: { type: 'string', minLength: 2, example: 'x', 'x-note': 'ignored' }, owner: { $ref: '#/components/schemas/Owner' } },
    },
    Owner: { type: 'object', properties: { id: { type: 'string', format: 'uuid' } } },
    Unused: { type: 'object', properties: { never: { type: 'string' } } },
  },
);

describe('generateRequestSchemas', () => {
  it('maps every operation with a JSON body to its schema and collects referenced schemas transitively', () => {
    const { bodies, schemas } = generateRequestSchemas(small);
    expect(bodies).toEqual({ create_thing: 'ThingCreate', inline_thing: 'operation:inline_thing' });
    expect(Object.keys(schemas)).toEqual(['Owner', 'ThingCreate', 'operation:inline_thing']);
  });

  it('keeps only validation keywords: descriptions, examples and extensions are dropped', () => {
    const { schemas } = generateRequestSchemas(small);
    expect(schemas.ThingCreate).toEqual({
      type: 'object',
      additionalProperties: false,
      required: ['name'],
      properties: { name: { type: 'string', minLength: 2 }, owner: { $ref: '#/components/schemas/Owner' } },
    });
    expect(schemas['operation:inline_thing']).toEqual({ type: 'object', additionalProperties: false, properties: { n: { type: 'integer' } } });
  });

  it('refuses a keyword it cannot enforce instead of validating more weakly than the schema says', () => {
    const doc = documentWith(
      { '/x': { post: { operationId: 'x', requestBody: json({ $ref: '#/components/schemas/Bad' }), responses: {} } } },
      { Bad: { type: 'object', properties: { a: { type: 'string', multipleOf: 2 } } } },
    );
    expect(() => generateRequestSchemas(doc)).toThrow('multipleOf');
    expect(() => generateRequestSchemas(doc)).toThrow('Bad');
  });

  it('fails on a reference to a schema that does not exist', () => {
    const doc = documentWith({ '/x': { post: { operationId: 'x', requestBody: json({ $ref: '#/components/schemas/Missing' }), responses: {} } } });
    expect(() => generateRequestSchemas(doc)).toThrow('Missing');
  });

  it('renders the same text every time, sorted, in ASCII only', () => {
    const first = renderRequestSchemasModule(generateRequestSchemas(small));
    expect(renderRequestSchemasModule(generateRequestSchemas(small))).toBe(first);
    expect(first.startsWith('// Generated by')).toBe(true);
    expect(first.indexOf('"Owner"')).toBeLessThan(first.indexOf('"ThingCreate"'));
    const accented = documentWith(
      { '/x': { post: { operationId: 'x', requestBody: json({ type: 'string', enum: ['đơn'] }), responses: {} } } },
    );
    expect(/^\p{ASCII}*$/u.test(renderRequestSchemasModule(generateRequestSchemas(accented)))).toBe(true);
  });
});

describe('the committed request schemas', () => {
  const doc = loadRealDocument();

  it('cover every operation of openapi.json that has a JSON request body', () => {
    const expected = listOperations(doc)
      .filter(({ operation }) => (operation.requestBody as { content?: Record<string, unknown> } | undefined)?.content?.['application/json'] !== undefined)
      .map(({ id }) => id)
      .sort();
    expect(expected.length).toBeGreaterThan(500);
    expect(Object.keys(REQUEST_BODIES).sort()).toEqual(expected);
  });

  it('are closed under references: every named schema and every $ref resolves', () => {
    const referenced = new Set<string>(Object.values(REQUEST_BODIES));
    const walk = (value: unknown): void => {
      if (Array.isArray(value)) value.forEach(walk);
      else if (typeof value === 'object' && value !== null) {
        for (const [key, member] of Object.entries(value)) {
          if (key === '$ref' && typeof member === 'string') referenced.add(member.replace('#/components/schemas/', ''));
          else walk(member);
        }
      }
    };
    walk(REQUEST_SCHEMAS);
    for (const name of referenced) expect(REQUEST_SCHEMAS).toHaveProperty([name]);
  });

  it('match what the generator produces from openapi.json, byte for byte (contracts:check)', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'machvon-validators-'));
    const spec = join(dir, 'openapi.json');
    writeFileSync(spec, JSON.stringify(doc));
    const logs: string[] = [];
    expect(await main(['--spec', spec, '--out', GENERATED_DIR, '--check'], { log: (line) => logs.push(line) })).toBe(0);
    expect(logs).toEqual([]);
    expect(readFileSync(join(GENERATED_DIR, REQUEST_SCHEMAS_FILE), 'utf8').replace(/\r\n/g, '\n')).toBe(renderRequestSchemasModule(generateRequestSchemas(doc)));
  }, 60_000);
});

describe('validateRequestBody', () => {
  it('returns undefined for an operation without a JSON body schema and issues otherwise', () => {
    expect(validateRequestBody('get_resources_organization_unit', {})).toBeUndefined();
    expect(requestSchemaOf('get_resources_organization_unit')).toBeUndefined();
    expect(requestSchemaOf('createCustomRole')).toBeDefined();
    expect(validateRequestBody('createCustomRole', { code: 'UNIT_CLERK', name: 'Clerk', permissions: ['iam.unit.manage'], rank: 35 })).toEqual([]);
  });

  it('applies the real schemas of the implemented commands', () => {
    const role = { code: 'UNIT_CLERK', name: 'Clerk', permissions: ['iam.unit.manage'], rank: 35 };
    expect(validateRequestBody('createCustomRole', { ...role, rank: 95 })).toEqual([{ kind: 'constraint', path: 'rank' }]);
    expect(validateRequestBody('createCustomRole', { ...role, is_system: true })).toEqual([{ kind: 'unknown_field', path: 'is_system' }]);
    expect(validateRequestBody('createCustomRole', { name: 'Clerk' })).toEqual([
      { kind: 'missing', path: 'code' },
      { kind: 'missing', path: 'permissions' },
      { kind: 'missing', path: 'rank' },
    ]);
    expect(validateRequestBody('moveOrganizationUnit', { new_parent_id: 'x', effective_from: '2026-02-31', reason: 'short' })).toEqual([
      { kind: 'constraint', path: 'new_parent_id' },
      { kind: 'constraint', path: 'effective_from' },
      { kind: 'constraint', path: 'reason' },
    ]);
  });
});
